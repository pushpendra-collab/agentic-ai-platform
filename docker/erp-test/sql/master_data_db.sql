-- InvenLogic master_data_db: the tables the agent reads, as the Schema Atlas (2026-10-29,
-- Flyway V31) lists them: same names, columns, types, NULLs and defaults. Foreign keys to
-- tables the agent never reads are left out. TEST replica only: never the real ERP.

CREATE OR REPLACE FUNCTION public.invenlogic_company_id() RETURNS bigint
    LANGUAGE sql STABLE
    AS $fn$ SELECT NULLIF(current_setting('invenlogic.company_id', true), '')::bigint $fn$;

CREATE TABLE public.uom (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id bigint NOT NULL,
    branch_id bigint,
    created_by bigint NOT NULL,
    updated_by bigint NOT NULL,
    code character varying(50) NOT NULL,
    name character varying(255) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    uqc_code character varying(10),
    decimal_places smallint NOT NULL DEFAULT 0
);

CREATE TABLE public.customer (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id bigint NOT NULL,
    branch_id bigint,
    created_by bigint NOT NULL,
    updated_by bigint NOT NULL,
    ledger_name character varying(255) NOT NULL,
    short_name character varying(255),
    display_name character varying(255),
    individual_or_company character varying(100),
    notes text,
    contact_person character varying(255),
    designation character varying(255),
    primary_mobile character varying(50),
    alt_mobile character varying(50),
    whatsapp character varying(50),
    primary_email character varying(255),
    alt_email character varying(255),
    website character varying(255),
    gst_applicable boolean NOT NULL DEFAULT false,
    gstin character varying(50),
    gst_registration_type character varying(100),
    gst_registration_date date,
    pan character varying(50),
    tan character varying(50),
    cin_llpin character varying(50),
    taxpayer_type character varying(100),
    tax_id character varying(100),
    tcs_applicable boolean NOT NULL DEFAULT false,
    tcs_section character varying(50),
    tcs_rate numeric(5,2),
    credit_limit numeric(15,2),
    credit_days integer,
    payment_terms character varying(255),
    price_list character varying(255),
    active boolean NOT NULL DEFAULT true,
    party_id bigint NOT NULL,
    payment_term_id bigint,
    customer_group_id bigint,
    price_list_id bigint,
    work_phone character varying(50),
    version bigint NOT NULL DEFAULT 0,
    cash_sale boolean NOT NULL DEFAULT false
);

CREATE TABLE public.product (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id bigint NOT NULL,
    branch_id bigint,
    created_by bigint NOT NULL,
    updated_by bigint NOT NULL,
    sku character varying(255) NOT NULL,
    name character varying(255) NOT NULL,
    description character varying(255),
    group_id bigint,
    category_id bigint,
    brand_id bigint,
    model character varying(255),
    hsn_code character varying(255),
    barcode character varying(255),
    active boolean NOT NULL DEFAULT true,
    model_id bigint,
    uom_id bigint REFERENCES public.uom (id),
    variant_parent_id bigint,
    variant_key character varying(100),
    tracked_by character varying(6) NOT NULL DEFAULT 'NONE'::character varying,
    batch_has_expiry boolean NOT NULL DEFAULT false,
    version bigint NOT NULL DEFAULT 0,
    is_service boolean NOT NULL DEFAULT false
);

CREATE TABLE public.warehouse (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id bigint NOT NULL,
    branch_id bigint NOT NULL,
    created_by bigint NOT NULL,
    updated_by bigint NOT NULL,
    code character varying(20) NOT NULL,
    name character varying(100) NOT NULL,
    address character varying(500),
    active boolean NOT NULL DEFAULT true,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    state_code character varying(2),
    pin_code character varying(6),
    parent_id bigint,
    not_for_sale boolean NOT NULL DEFAULT false
);

DO $rls$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['uom', 'customer', 'product', 'warehouse'] LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format(
            'CREATE POLICY tenant_isolation ON public.%I USING (company_id = invenlogic_company_id())'
            ' WITH CHECK (company_id = invenlogic_company_id())', t);
        EXECUTE format('ALTER TABLE public.%I OWNER TO master_data_owner', t);
        EXECUTE format('GRANT SELECT ON public.%I TO agentic_erp_reader', t);
    END LOOP;
END
$rls$;
