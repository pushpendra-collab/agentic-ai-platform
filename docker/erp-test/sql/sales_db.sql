CREATE TABLE public.receivable_allocation (
    id bigserial PRIMARY KEY,
    company_id bigint NOT NULL,
    branch_id bigint NOT NULL,
    created_by bigint NOT NULL,
    updated_by bigint NOT NULL,
    sales_receipt_id bigint,
    sales_credit_note_id bigint,
    sales_invoice_id bigint,
    sales_opening_bill_id bigint,
    amount numeric(19,2) NOT NULL,
    allocated_by bigint NOT NULL,
    allocated_at timestamp with time zone NOT NULL DEFAULT now(),
    undone_by bigint,
    undone_at timestamp with time zone,
    sales_refund_id bigint,
    FOREIGN KEY (company_id, sales_receipt_id) REFERENCES public.sales_receipt (company_id, id),
    FOREIGN KEY (company_id, sales_credit_note_id)
        REFERENCES public.sales_credit_note (company_id, id),
    FOREIGN KEY (company_id, sales_invoice_id) REFERENCES public.sales_invoice (company_id, id),
    FOREIGN KEY (company_id, sales_opening_bill_id)
        REFERENCES public.sales_opening_bill (company_id, id)
);

DO $rls$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['sales_receipt', 'sales_invoice', 'sales_opening_bill',
                             'sales_credit_note', 'receivable_allocation'] LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format(
            'CREATE POLICY tenant_isolation ON public.%I USING (company_id = invenlogic_company_id())'
            ' WITH CHECK (company_id = invenlogic_company_id())', t);
        EXECUTE format('ALTER TABLE public.%I OWNER TO sales_owner', t);
        EXECUTE format('GRANT SELECT ON public.%I TO agentic_erp_reader', t);
    END LOOP;
END
$rls$;
